# ── File paths ────────────────────────────────────────────────────────────────
# CSV_PATH  : docking_summary.csv produced by Stage 6
# OUT_DIR   : where the two PNG figures will be saved (same folder)
CSV_PATH = os.path.join(STAGE6_DIR, "docking_summary.csv")
OUT_DIR  = STAGE6_DIR

# ── Score columns ─────────────────────────────────────────────────────────────
SCORE_COLS = ["CNNaffinity", "minimizedAffinity", "CNNscore"]

SCORE_LABELS = {
    "CNNaffinity":       "CNN Affinity  (–log Kd/Ki)  ↑ higher = better",
    "minimizedAffinity": "Vinardo Score  (kcal mol⁻¹)  ↓ more negative = better",
    "CNNscore":          "CNN Score  (probability)  ↑ higher = better",
}

# minimizedAffinity is the only score where lower (more negative) = better
LOWER_IS_BETTER = {"minimizedAffinity"}

# ── Colours ───────────────────────────────────────────────────────────────────
# One colour per score panel
PANEL_COLORS = {
    "CNNaffinity":       "#2E86AB",   # steel blue
    "minimizedAffinity": "#E84855",   # crimson
    "CNNscore":          "#3BB273",   # green
}

# Gold / silver / bronze for top-3 ranked molecules
RANK_COLORS = {
    1: "#D4A017",   # gold
    2: "#8A8A8A",   # silver
    3: "#A0522D",   # bronze
}

print("✅  Cell 1 ready — imports and config loaded.")
print(f"   CSV expected at : {CSV_PATH}")
print(f"   Figures saved to: {OUT_DIR}")

# ════════════════════════════════════════════════════════════════════
#  STAGE 6 VISUALISATION — CELL 2 of 5
#  Load docking_summary.csv, clean scores, rank molecules
#
#  What this cell does:
#    1. Reads docking_summary.csv produced by Stage 6
#    2. Converts score columns to numeric (handles empty strings from GNINA)
#    3. Keeps only pose 1 per molecule — GNINA ranks pose 1 highest
#    4. Ranks all molecules: CNNaffinity is the primary metric,
#       minimizedAffinity is the tiebreaker
#    5. Builds a short mol_label for the chart y-axis
#       e.g.  "EAM-A-1  mol-3"
# ════════════════════════════════════════════════════════════════════

if not os.path.exists(CSV_PATH):
    raise FileNotFoundError(
        f"docking_summary.csv not found.\nRun Stage 6 first.\nExpected: {CSV_PATH}"
    )

df_raw = pd.read_csv(CSV_PATH)

# Coerce score columns — GNINA writes empty string when a property is missing
for c in SCORE_COLS:
    df_raw[c] = pd.to_numeric(df_raw[c], errors="coerce")

# Keep best pose only (pose 1 = GNINA top-ranked pose)
df = df_raw[df_raw["pose"] == 1].copy().reset_index(drop=True)

# Rank: CNNaffinity primary (higher = better),
#       minimizedAffinity tiebreak (lower = better, so subtract)
df["_rank_key"] = df["CNNaffinity"] - 0.01 * df["minimizedAffinity"]
df = df.sort_values("_rank_key", ascending=False).reset_index(drop=True)
df["rank"] = range(1, len(df) + 1)

# Clean y-axis label
df["mol_label"] = (
    df["ligand_group"].str.replace("_", " ", regex=False)
    + "  mol-" + df["mol_idx"].astype(str)
)

print(f"✅  Cell 2 ready — data loaded and ranked.")
print(f"   Molecules     : {len(df)}")
print(f"   Ligand groups : {df['ligand_group'].nunique()}")
print(f"   Score columns : {SCORE_COLS}")
print()
print(df[["rank", "mol_label", "CNNaffinity", "minimizedAffinity", "CNNscore"]].to_string(index=False))

# ════════════════════════════════════════════════════════════════════
#  STAGE 6 VISUALISATION — CELL 3 of 5
#  Table helper function  draw_table()
#
#  What this cell does:
#    Defines draw_table(ax, df_plot) which draws a styled summary
#    table into a matplotlib axes. It is called once per figure
#    (top-10 figure and all-molecules figure).
#
#  Table layout:
#    Columns : Rank | Molecule | CNNaff ↑ | Vinardo ↓ | CNNsc ↑ | SMILES
#    Header  : dark navy background, white bold text
#    Row 1–3 : gold / silver / bronze tint with bold text
#    Row 4+  : alternating white / light grey
#    SMILES  : truncated to 30 characters to fit the column
# ════════════════════════════════════════════════════════════════════

def draw_table(ax, df_plot):
    ax.axis("off")

    tbl_data = []
    for _, row in df_plot.iterrows():
        smi = textwrap.shorten(str(row["smiles"]), width=30, placeholder="…")
        tbl_data.append([
            str(int(row["rank"])),
            row["mol_label"],
            f"{row['CNNaffinity']:.3f}",
            f"{row['minimizedAffinity']:.3f}",
            f"{row['CNNscore']:.3f}",
            smi,
        ])

    headers = ["Rank", "Molecule", "CNNaff ↑", "Vinardo ↓", "CNNsc ↑", "SMILES"]
    col_w   = [0.06, 0.17, 0.11, 0.11, 0.09, 0.46]

    tbl = ax.table(cellText=tbl_data, colLabels=headers,
                   loc="center", cellLoc="center")
    tbl.auto_set_font_size(False)
    tbl.set_fontsize(7)

    # Header row styling
    for j in range(len(headers)):
        c = tbl[0, j]
        c.set_facecolor("#1A1A2E")
        c.set_text_props(color="white", fontweight="bold", fontsize=7.5)
        c.set_edgecolor("#FAFAFA")
        c.set_width(col_w[j])

    # Data row styling
    hi = ["#D4A017", "#8A8A8A", "#A0522D"]   # gold / silver / bronze
    for ri in range(1, len(tbl_data) + 1):
        for ci in range(len(headers)):
            cell = tbl[ri, ci]
            if ri <= 3:
                cell.set_facecolor(hi[ri - 1] + "44")   # 27% alpha tint
                cell.set_text_props(fontweight="bold")
            elif ri % 2 == 0:
                cell.set_facecolor("#F0F4F8")
            else:
                cell.set_facecolor("#FFFFFF")
            cell.set_edgecolor("#E0E0E0")
            cell.set_width(col_w[ci])

    ax.set_title("Summary Table  (best pose per molecule)",
                 fontsize=9, fontweight="bold", pad=6, color="#1A1A2E")

print("✅  Cell 3 ready — draw_table() defined.")

# ════════════════════════════════════════════════════════════════════
#  STAGE 6 VISUALISATION — CELL 4 of 5
#  Main figure builder  make_barchart_figure()
#
#  What this cell does:
#    Defines make_barchart_figure(df_plot, title_tag, figname)
#    which builds one complete figure containing:
#
#    LEFT  — 3 horizontal bar chart panels, one per GNINA score:
#              • CNNaffinity        (blue bars)
#              • minimizedAffinity  (red bars)
#              • CNNscore           (green bars)
#            All three panels share the same molecule y-axis.
#            Bars are coloured gold/silver/bronze for ranks 1/2/3,
#            and the panel colour for all other molecules.
#            Exact numeric value printed at the end of every bar.
#
#    RIGHT — styled summary table (drawn by draw_table() from Cell 3)
#
#    BOTTOM — colour-key legend strip in a fixed position below all
#             panels so it never overlaps the bars or the table.
#
#  Figure height auto-scales based on the number of molecules so
#  labels are never squashed regardless of dataset size.
# ════════════════════════════════════════════════════════════════════

def make_barchart_figure(df_plot, title_tag, figname):
    n     = len(df_plot)
    row_h = 0.54 if n <= 10 else 0.38
    fig_h = max(7.5, n * row_h + 3.8)

    fig = plt.figure(figsize=(20, fig_h), facecolor="#FAFAFA")

    # Two-row outer layout: content row + thin legend row
    outer = gridspec.GridSpec(
        2, 1, figure=fig,
        height_ratios=[1, 0.001],
        hspace=0,
        left=0.01, right=0.99,
        top=0.93, bottom=0.09,
    )
    # Four-column inner layout inside the content row
    inner = gridspec.GridSpecFromSubplotSpec(
        1, 4, subplot_spec=outer[0],
        width_ratios=[1, 1, 1, 1.65],
        wspace=0.10,
    )
    axes_bar = [fig.add_subplot(inner[0, i]) for i in range(3)]
    ax_table = fig.add_subplot(inner[0, 3])

    fig.suptitle(
        f"BRD4 Molecular Docking — Scores per Molecule  [{title_tag}]",
        fontsize=14, fontweight="bold", y=0.97, color="#1A1A2E"
    )

    y_pos    = np.arange(n)
    y_labels = df_plot["mol_label"].tolist()

    for i, col in enumerate(SCORE_COLS):
        ax    = axes_bar[i]
        color = PANEL_COLORS[col]
        vals  = df_plot[col].values

        # Bar colour: gold/silver/bronze top 3, panel colour for the rest
        bar_colors = [
            RANK_COLORS.get(int(row["rank"]), color)
            for _, row in df_plot.iterrows()
        ]

        # Zero reference line for Vinardo (bars extend left into negative)
        if col in LOWER_IS_BETTER:
            ax.axvline(0, color="#999999", linewidth=0.8, alpha=0.5)

        ax.barh(y_pos, vals, color=bar_colors,
                edgecolor="white", linewidth=0.5,
                height=0.65, alpha=0.88)

        # Numeric value label just outside bar end
        x_range = float(np.nanmax(np.abs(vals))) or 1.0
        offset  = x_range * 0.025
        for yi, v in zip(y_pos, vals):
            if not np.isfinite(v):
                continue
            ha   = "left"  if v >= 0 else "right"
            xpos = v + (offset if v >= 0 else -offset)
            ax.text(xpos, yi, f"{v:.2f}",
                    va="center", ha=ha, fontsize=6.8, color="#222222",
                    fontweight="bold" if yi < 3 else "normal")

        # Faint horizontal row dividers
        for yi in y_pos:
            ax.axhline(yi, color="#EBEBEB", linewidth=0.4, zorder=0)

        ax.set_yticks(y_pos)
        if i == 0:
            ax.set_yticklabels(y_labels, fontsize=7.5, color="#222222")
        else:
            ax.set_yticklabels([])

        ax.invert_yaxis()
        ax.set_xlabel(SCORE_LABELS[col], fontsize=8, labelpad=5)
        ax.tick_params(axis="x", labelsize=7.5)
        ax.spines[["top", "right"]].set_visible(False)
        ax.spines["left"].set_color("#CCCCCC")
        ax.spines["bottom"].set_color("#AAAAAA")
        ax.set_facecolor("#FAFAFA")
        ax.xaxis.set_major_formatter(mticker.FormatStrFormatter("%.1f"))

        direction = "▼ lower = better" if col in LOWER_IS_BETTER else "▲ higher = better"
        ax.set_title(f"{col}\n{direction}",
                     fontsize=9, fontweight="bold", color=color, pad=4)

    axes_bar[0].set_ylabel("Molecule  (ranked by CNN affinity)",
                            fontsize=9, labelpad=8, color="#555")

    # ── Summary table ──────────────────────────────────────────────────────────
    draw_table(ax_table, df_plot)

    # ── Legend strip — fixed axes below all panels, never overlaps ────────────
    ax_leg = fig.add_axes([0.13, 0.01, 0.55, 0.055])
    ax_leg.axis("off")
    legend_patches = [
        mpatches.Patch(color=RANK_COLORS[1], label="Rank 1  (best)"),
        mpatches.Patch(color=RANK_COLORS[2], label="Rank 2"),
        mpatches.Patch(color=RANK_COLORS[3], label="Rank 3"),
        mpatches.Patch(color="#2E86AB", alpha=0.7, label="Other — CNNaffinity panel"),
        mpatches.Patch(color="#E84855", alpha=0.7, label="Other — Vinardo panel"),
        mpatches.Patch(color="#3BB273", alpha=0.7, label="Other — CNNscore panel"),
    ]
    ax_leg.legend(
        handles=legend_patches,
        loc="center left", ncol=6,
        fontsize=7.5, frameon=True,
        framealpha=0.85, edgecolor="#CCCCCC",
        title="Bar colour key", title_fontsize=7.5,
    )

    # ── Footnote ──────────────────────────────────────────────────────────────
    fig.text(
        0.72, 0.025,
        "Ranking: CNNaffinity (primary) + Vinardo (tiebreak)\n"
        "Best pose (pose 1) per molecule | GNINA v1.0.3",
        fontsize=6.5, color="#888888", style="italic", ha="left", va="center"
    )

    out_path = os.path.join(OUT_DIR, figname)
    fig.savefig(out_path, dpi=180, bbox_inches="tight", facecolor="#FAFAFA")
    plt.show()
    print(f"  💾 Saved: {out_path}")

print("✅  Cell 4 ready — make_barchart_figure() defined.")

