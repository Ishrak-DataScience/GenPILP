def _safe(s: str) -> str:
    """Convert a ligand ID to a safe folder name (same logic as Stage 2/3/4)."""
    return "".join(ch if ch.isalnum() or ch in "._-" else "_" for ch in s)


def _read_smiles_from_txt(path: str) -> List[str]:
    """
    Read valid SMILES (one per line) from a Stage-2 prediction txt file.
    Lines that RDKit cannot parse are silently skipped.
    """
    valid = []
    try:
        with open(path, encoding="utf-8") as f:
            for line in f:
                smi = line.strip()
                if smi and Chem.MolFromSmiles(smi) is not None:
                    valid.append(smi)
    except Exception as e:
        print(f"  ⚠️  Could not read {path}: {e}")
    return valid


def load_ligand_predictions(
    lig_dir: str,
) -> Dict[int, Dict[str, List[str]]]:
    """
    Discover ia_mask*.txt and rand_mask*.txt files under lig_dir.
    Returns {mask_count: {"ia": [smiles…], "rand": [smiles…]}}.
    """
    result: Dict[int, Dict[str, List[str]]] = {}

    ia_pattern   = os.path.join(lig_dir, "ia_mask*.txt")
    rand_pattern = os.path.join(lig_dir, "rand_mask*.txt")

    def _extract_count(path: str) -> Optional[int]:
        m = re.search(r"mask(\d+)\.txt$", os.path.basename(path))
        return int(m.group(1)) if m else None

    for path in sorted(glob.glob(ia_pattern)):
        mc = _extract_count(path)
        if mc is None:
            continue
        result.setdefault(mc, {"ia": [], "rand": []})
        result[mc]["ia"] = _read_smiles_from_txt(path)

    for path in sorted(glob.glob(rand_pattern)):
        mc = _extract_count(path)
        if mc is None:
            continue
        result.setdefault(mc, {"ia": [], "rand": []})
        result[mc]["rand"] = _read_smiles_from_txt(path)

    return result


def pool_smiles(
    ia_list: List[str],
    rand_list: List[str],
    deduplicate: bool,
) -> List[str]:
    """
    Combine IA and random SMILES into one list.
    If deduplicate=True, each unique SMILES string appears once.
    """
    combined = ia_list + rand_list
    if deduplicate:
        seen, out = set(), []
        for smi in combined:
            if smi not in seen:
                seen.add(smi)
                out.append(smi)
        return out
    return combined


def load_pool_for_ligand(
    lig_dir: str,
    pool_choice: str,
) -> List[str]:
    """
    Load generated SMILES for one ligand folder according to pool_choice.

    pool_choice : 'ia'   → ia_mask*.txt only
                  'rand' → rand_mask*.txt only
                  'both' → IA + random, deduplicated
    """
    predictions = load_ligand_predictions(lig_dir)
    mask_counts = sorted(predictions.keys())

    if pool_choice == "ia":
        all_smi = [s for mc in mask_counts for s in predictions[mc]["ia"]]
    elif pool_choice == "rand":
        all_smi = [s for mc in mask_counts for s in predictions[mc]["rand"]]
    else:   # "both"
        ia   = [s for mc in mask_counts for s in predictions[mc]["ia"]]
        rand = [s for mc in mask_counts for s in predictions[mc]["rand"]]
        all_smi = pool_smiles(ia, rand, deduplicate=True)

    valid = [s for s in all_smi if Chem.MolFromSmiles(s) is not None]
    return valid


